#!/usr/bin/env python3
"""Deterministic synthetic Matrix Market generator for SpMVBench.

Produces a fixed, seeded set of matrices into ``data/`` plus an optional
downloader for real SuiteSparse matrices.

Run:
    python3 tools/gen_matrices.py
    python3 tools/gen_matrices.py --suitesparse cage10
"""

from __future__ import annotations

import argparse
import os
import sys
import tarfile
import tempfile
import urllib.request

import numpy as np

DATA_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "data")

# SuiteSparse group names for the matrices we know how to fetch.
SUITESPARSE_GROUPS = {
    "cage10": "vanHeukelum",
    "cage11": "vanHeukelum",
    "cage12": "vanHeukelum",
    "consph": "DNVS",
    "cfd1": "Rothberg",
    "cfd2": "Rothberg",
}
SUITESPARSE_MIRRORS = (
    "https://suitesparse-collection-website.herokuapp.com/MM/{group}/{name}.tar.gz",
    "https://sparse.tamu.edu/MM/{group}/{name}.tar.gz",
)


def write_mtx(path: str, nrows: int, ncols: int, I, J, V) -> None:
    """Write a 1-based coordinate real general .mtx file."""
    I = np.asarray(I, dtype=np.int64)
    J = np.asarray(J, dtype=np.int64)
    V = np.asarray(V, dtype=np.float64)
    if not (len(I) == len(J) == len(V)):
        raise ValueError("I, J, V must have the same length")
    with open(path, "w", encoding="ascii") as f:
        f.write("%%MatrixMarket matrix coordinate real general\n")
        f.write(f"% generated by tools/gen_matrices.py\n")
        f.write(f"{nrows} {ncols} {len(I)}\n")
        # Batch-write for speed.
        rows = np.column_stack([I, J])
        buf = []
        chunk = 200000
        for start in range(0, len(I), chunk):
            end = min(start + chunk, len(I))
            for k in range(start, end):
                buf.append(f"{rows[k,0]} {rows[k,1]} {V[k]:.17g}\n")
            f.write("".join(buf))
            buf.clear()


def sort_csr(nrows: int, cols, vals):
    """Given per-row column and value lists, return globally sorted 1-based arrays."""
    I, J, V = [], [], []
    for i in range(nrows):
        c = np.asarray(cols[i], dtype=np.int64)
        v = np.asarray(vals[i], dtype=np.float64)
        order = np.argsort(c)
        c = c[order]
        v = v[order]
        if len(c):
            I.append(np.full(len(c), i + 1, dtype=np.int64))
            J.append(c + 1)
            V.append(v)
    if not I:
        return np.array([], dtype=np.int64), np.array([], dtype=np.int64), np.array([], dtype=np.float64)
    return np.concatenate(I), np.concatenate(J), np.concatenate(V)


def gen_banded_100k() -> str:
    n = 100000
    offsets = [0, 1, -1, 1000, -1000]  # 5-point-stencil-like band
    rng = np.random.default_rng(1001)
    I, J, V = [], [], []
    for off in offsets:
        rows = np.arange(max(0, -off), min(n, n - off))
        cols = rows + off
        I.append(rows + 1)
        J.append(cols + 1)
        V.append(rng.uniform(0.5, 1.5, size=len(rows)))
    I = np.concatenate(I)
    J = np.concatenate(J)
    V = np.concatenate(V)
    order = np.lexsort((J, I))
    path = os.path.join(DATA_DIR, "banded_100k.mtx")
    write_mtx(path, n, n, I[order], J[order], V[order])
    return path


def gen_uniform_random() -> str:
    rows = 50000
    cols = 50000
    per_row = 20
    rng = np.random.default_rng(2002)
    rcol, rval = [], []
    for _ in range(rows):
        c = rng.choice(cols, size=per_row, replace=False)
        v = rng.uniform(-1.0, 1.0, size=per_row)
        rcol.append(c)
        rval.append(v)
    I, J, V = sort_csr(rows, rcol, rval)
    path = os.path.join(DATA_DIR, "uniform_random.mtx")
    write_mtx(path, rows, cols, I, J, V)
    return path


def gen_powerlaw_skew() -> str:
    rows = 30000
    cols = 30000
    rng = np.random.default_rng(3003)
    # Pareto-distributed row lengths -> heavy tail and large max/mean ratio.
    raw = rng.pareto(1.2, size=rows) * 8.0 + 1.0
    lens = np.clip(raw.astype(np.int64), 1, 8000)
    rcol, rval = [], []
    for i in range(rows):
        L = int(lens[i])
        c = rng.choice(cols, size=L, replace=False)
        v = rng.uniform(0.1, 2.0, size=L)
        rcol.append(c)
        rval.append(v)
    I, J, V = sort_csr(rows, rcol, rval)
    path = os.path.join(DATA_DIR, "powerlaw_skew.mtx")
    write_mtx(path, rows, cols, I, J, V)
    return path


def gen_diag_dominant_small() -> str:
    n = 2000
    per_row = 8
    rng = np.random.default_rng(4004)
    rcol, rval = [], []
    for i in range(n):
        # Sample off-diagonal columns from range(n) excluding the diagonal so
        # the explicit diagonal entry never duplicates an off-diagonal one.
        c = rng.choice(n - 1, size=per_row - 1, replace=False)
        c = np.where(c >= i, c + 1, c)
        v = rng.uniform(-1.0, 1.0, size=per_row - 1)
        rcol.append(c)
        rval.append(v)
    I, J, V = sort_csr(n, rcol, rval)
    # Insert diagonal to make it diagonally dominant: a_ii = 1 + sum |a_ij|.
    # Rebuild per row with the diagonal present.
    Ilist, Jlist, Vlist = [], [], []
    rowptr = np.searchsorted(I, np.arange(1, n + 2))
    for i in range(n):
        s = rowptr[i]
        e = rowptr[i + 1]
        rr = I[s:e]
        cc = J[s:e]
        vv = V[s:e]
        offsum = float(np.sum(np.abs(vv)))
        diag = 1.0 + offsum
        cc = np.append(cc, i + 1)
        vv = np.append(vv, diag)
        order = np.argsort(cc)
        Ilist.append(np.full(len(cc), i + 1, dtype=np.int64))
        Jlist.append(cc[order])
        Vlist.append(vv[order])
    I2 = np.concatenate(Ilist)
    J2 = np.concatenate(Jlist)
    V2 = np.concatenate(Vlist)
    path = os.path.join(DATA_DIR, "diag_dominant_small.mtx")
    write_mtx(path, n, n, I2, J2, V2)
    return path


def gen_tiny_3x3() -> str:
    n = 3
    I = np.array([1, 1, 2, 3, 3], dtype=np.int64)
    J = np.array([1, 3, 2, 1, 3], dtype=np.int64)
    V = np.array([2.0, 1.0, 3.0, 4.0, 5.0], dtype=np.float64)
    path = os.path.join(DATA_DIR, "tiny_3x3.mtx")
    write_mtx(path, n, n, I, J, V)
    return path


def fetch_suitesparse(name: str) -> str | None:
    group = SUITESPARSE_GROUPS.get(name)
    if group is None:
        print(f"[suitesparse] unknown matrix '{name}' (known: {sorted(SUITESPARSE_GROUPS)})")
        return None
    dest = os.path.join(DATA_DIR, f"{name}.mtx")
    if os.path.exists(dest):
        print(f"[suitesparse] {dest} already exists, skipping download")
        return dest
    last_err = None
    for tmpl in SUITESPARSE_MIRRORS:
        url = tmpl.format(group=group, name=name)
        try:
            print(f"[suitesparse] trying {url}")
            with tempfile.TemporaryDirectory() as td:
                tarpath = os.path.join(td, f"{name}.tar.gz")
                urllib.request.urlretrieve(url, tarpath)
                with tarfile.open(tarpath, "r:gz") as tar:
                    members = [m for m in tar.getmembers() if m.name.endswith(".mtx")]
                    if not members:
                        raise RuntimeError("no .mtx inside tarball")
                    tar.extractall(td, members=members)
                    src = os.path.join(td, members[0].name)
                    with open(src, "r", encoding="ascii", errors="replace") as f:
                        data = f.read()
                with open(dest, "w", encoding="ascii") as f:
                    f.write(data)
            print(f"[suitesparse] wrote {dest}")
            return dest
        except Exception as exc:  # noqa: BLE001 - network can fail in any way
            last_err = exc
            print(f"[suitesparse] failed: {exc}")
    print(f"[suitesparse] could not download '{name}' ({last_err}); "
          f"continuing with synthetic matrices only")
    return None


def main() -> int:
    ap = argparse.ArgumentParser(description="Generate SpMVBench matrices")
    ap.add_argument("--suitesparse", metavar="NAME", action="append", default=[],
                    help="also download a SuiteSparse matrix (e.g. cage10, consph)")
    args = ap.parse_args()

    os.makedirs(DATA_DIR, exist_ok=True)

    for fn in (gen_banded_100k, gen_uniform_random, gen_powerlaw_skew,
               gen_diag_dominant_small, gen_tiny_3x3):
        path = fn()
        size = os.path.getsize(path)
        print(f"[gen] {os.path.basename(path):24s} {size/1e6:8.2f} MB")

    for name in args.suitesparse:
        fetch_suitesparse(name)

    print("[gen] done")
    return 0


if __name__ == "__main__":
    sys.exit(main())
