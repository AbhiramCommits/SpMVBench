#!/usr/bin/env python3
"""Build results/summary.md from bench.csv, accuracy.csv and heuristic.csv.

Emits:
  results/summary.md  headline tables (best kernel per matrix/precision,
                      heuristic accuracy, speedup extremes, accuracy summary)
  results/gflops.png  best-kernel GFLOP/s bar chart (if matplotlib present)

Run:
    python3 tools/report.py
"""

from __future__ import annotations

import csv
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RESULTS = os.path.join(ROOT, "results")

SPMV_KERNELS = {"csr_scalar", "csr_vector", "csr_merge", "ell", "bcsr"}
# The 3x3 matrix is a correctness fixture; its times are below useful timer
# resolution, so it is excluded from the performance headline.
SKIP_MATRICES = {"tiny_3x3"}


def read_csv(path):
    if not os.path.exists(path):
        return []
    with open(path, newline="", encoding="ascii") as f:
        return list(csv.DictReader(f))


def fmt(x, nd=4):
    try:
        return f"{float(x):.{nd}g}"
    except (TypeError, ValueError):
        return str(x)


def build_summary():
    bench = read_csv(os.path.join(RESULTS, "bench.csv"))
    acc = read_csv(os.path.join(RESULTS, "accuracy.csv"))
    heur = read_csv(os.path.join(RESULTS, "heuristic.csv"))

    lines = []
    lines.append("# SpMVBench summary\n")
    lines.append("Generated by `tools/report.py` from the committed artifacts in "
                 "`results/`. All numbers are measured on this machine.\n")

    # ---- headline: best SpMV kernel per matrix x precision ------------------
    lines.append("## Headline: best kernel per matrix and precision\n")
    lines.append("Speedup and all throughput numbers use the minimum time over "
                 "iterations (best case), measured against the single-threaded "
                 "CPU `csr_scalar` baseline (no GPU on this machine).\n")
    lines.append("| matrix | prec | best kernel | min ms | mean ms | GFLOP/s | "
                 "BW lo GB/s | BW hi GB/s | speedup |")
    lines.append("|--------|------|-------------|-------:|--------:|--------:|"
                 "-----------:|-----------:|--------:|")
    # Select the best kernel by the minimum (least noisy) time; display the mean.
    best_rows = {}
    for r in bench:
        if r["kernel"] not in SPMV_KERNELS or r["matrix"] in SKIP_MATRICES:
            continue
        key = (r["matrix"], r["precision"])
        cur = best_rows.get(key)
        if cur is None or float(r["min_ms"]) < float(cur["min_ms"]):
            best_rows[key] = r
    for key in sorted(best_rows):
        r = best_rows[key]
        lines.append(
            f"| {r['matrix']} | {r['precision']} | {r['kernel']} | "
            f"{fmt(r['min_ms'],4)} | {fmt(r['mean_ms'],4)} | "
            f"{fmt(r['gflops'],4)} | {fmt(r['bw_lo_gbs'],4)} | "
            f"{fmt(r['bw_hi_gbs'],4)} | {fmt(r['speedup_vs_st'],3)}x |"
        )

    # ---- speedup extremes ---------------------------------------------------
    if bench:
        ranked = sorted(
            (r for r in bench
             if float(r["speedup_vs_st"]) > 0.0 and r["matrix"] not in SKIP_MATRICES),
            key=lambda r: float(r["speedup_vs_st"]), reverse=True)
        lines.append("\n## Speedup vs single-thread baseline - extremes\n")
        lines.append("| matrix | prec | kernel | speedup |")
        lines.append("|--------|------|--------|--------:|")
        for r in ranked[:3] + ranked[-3:]:
            lines.append(
                f"| {r['matrix']} | {r['precision']} | {r['kernel']} | "
                f"{fmt(r['speedup_vs_st'],3)}x |"
            )

    # ---- heuristic ----------------------------------------------------------
    lines.append("\n## Heuristic vs measured oracle\n")
    if heur:
        hits = sum(1 for r in heur if r["hit"] == "1")
        n = len(heur)
        worst = 0.0
        worst_name = ""
        for r in heur:
            s = float(r["slowdown"])
            if s > worst:
                worst, worst_name = s, r["matrix"]
        pct = 100.0 * hits / n if n else 0.0
        lines.append(f"`choose_spmv` selected the fastest measured kernel on "
                     f"**{hits}/{n} = {pct:.0f}%** of matrices; worst-case slowdown "
                     f"when it missed was **{worst:.2f}x** ({worst_name}).\n")
        lines.append("| matrix | chosen | oracle best | chosen ms | best ms | hit | slowdown |")
        lines.append("|--------|--------|-------------|----------:|--------:|-----|---------:|")
        for r in heur:
            lines.append(
                f"| {r['matrix']} | {r['chosen']} | {r['oracle_best']} | "
                f"{fmt(r['chosen_ms'])} | {fmt(r['best_ms'])} | "
                f"{'yes' if r['hit']=='1' else 'no'} | {fmt(r['slowdown'],3)}x |"
            )
    else:
        lines.append("_results/heuristic.csv not found_\n")

    # ---- accuracy -----------------------------------------------------------
    lines.append("\n## Accuracy (max relative error, CSR SpMV)\n")
    if acc:
        lines.append("| matrix | fp32/fp32 | fp32/fp64 | fp64/fp64 |")
        lines.append("|--------|-----------|-----------|-----------|")
        modes = ["fp32/fp32", "fp32/fp64", "fp64/fp64"]
        by = {}
        for r in acc:
            if r["kernel"] != "csr_vector":
                continue
            by.setdefault(r["matrix"], {})[r["mode"]] = r["max_rel_err"]
        for m in sorted(by):
            cells = " | ".join(fmt(by[m].get(mode, "n/a"),4) for mode in modes)
            lines.append(f"| {m} | {cells} |")
        lines.append("\nSee `docs/error_analysis.md` for the full discussion and "
                     "the error-bound comparison.\n")
    else:
        lines.append("_results/accuracy.csv not found_\n")

    return "\n".join(lines) + "\n", best_rows


def make_plot(best_rows):
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except Exception as exc:  # noqa: BLE001
        print(f"[report] matplotlib unavailable ({exc}); skipping gflops.png")
        return
    labels, vals = [], []
    for (matrix, prec), r in sorted(best_rows.items()):
        if prec != "fp64":
            continue
        labels.append(matrix)
        vals.append(float(r["gflops"]))
    if not labels:
        return
    fig, ax = plt.subplots(figsize=(8, 4.5))
    ax.bar(labels, vals, color="#3572A5")
    ax.set_ylabel("GFLOP/s (best fp64 SpMV kernel)")
    ax.set_title("SpMVBench best-kernel throughput")
    plt.xticks(rotation=25, ha="right")
    fig.tight_layout()
    out = os.path.join(RESULTS, "gflops.png")
    fig.savefig(out, dpi=120)
    print(f"[report] wrote {out}")


def main() -> int:
    os.makedirs(RESULTS, exist_ok=True)
    summary, best_rows = build_summary()
    with open(os.path.join(RESULTS, "summary.md"), "w", encoding="ascii") as f:
        f.write(summary)
    print("[report] wrote results/summary.md")
    make_plot(best_rows)
    return 0


if __name__ == "__main__":
    sys.exit(main())
