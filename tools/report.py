#!/usr/bin/env python3
"""Build results/summary.md from the methodology-fixed benchmark artifacts.

Inputs:
  results/bench.csv       device,matrix,precision,kernel,is_baseline,median_ms,
                          min_ms,mean_ms,max_ms,gflops,bw_lo_gbs,bw_hi_gbs,
                          bw_pct_peak,transfer_ms,speedup,baseline
  results/heuristic.csv   matrix,device,chosen,oracle_best,chosen_ms,best_ms,
                          hit,slowdown
  results/accuracy.csv    matrix,kernel,mode,max_rel_err,l2_rel_err,max_abs_err

Emits results/summary.md and results/gflops.png (if matplotlib exists).
"""

from __future__ import annotations

import csv
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RESULTS = os.path.join(ROOT, "results")

# The 3x3 fixture is below useful timer resolution.
SKIP_MATRICES = {"tiny_3x3"}


def read_csv(path):
    if not os.path.exists(path):
        return []
    with open(path, newline="", encoding="ascii") as f:
        return list(csv.DictReader(f))


def fmt(x, nd=4):
    try:
        return f"{float(x):.{nd}g}"
    except (TypeError, ValueError):
        return str(x)


def is_true(v):
    return str(v).strip() in ("1", "true", "True", "yes")


def device_label(d):
    return "GPU" if d == "cuda" else "CPU"


def build_summary():
    bench = read_csv(os.path.join(RESULTS, "bench.csv"))
    acc = read_csv(os.path.join(RESULTS, "accuracy.csv"))
    heur = read_csv(os.path.join(RESULTS, "heuristic.csv"))

    gpu_info = {}
    info_path = os.path.join(RESULTS, "gpu_info.txt")
    if os.path.exists(info_path):
        for line in open(info_path, encoding="ascii"):
            if "=" in line:
                k, v = line.strip().split("=", 1)
                gpu_info[k] = v

    hardware = {}
    hardware_path = os.path.join(RESULTS, "hardware.txt")
    if os.path.exists(hardware_path):
        for line in open(hardware_path, encoding="ascii"):
            if "=" in line:
                k, v = line.strip().split("=", 1)
                hardware[k] = v

    lines = []
    lines.append("# SpMVBench summary\n")
    lines.append("Generated by `tools/report.py` from the committed artifacts in "
                 "`results/`.\n")
    lines.append("**Baselines:** CPU = multithreaded OpenMP `csr_scalar_omp` "
                 "(single-thread `csr_scalar_1t` shown only as context); GPU = "
                 "`cusparse_spmv` / `cusparse_spmm`. Baseline rows are not "
                 "compared against themselves.\n")
    cpu_host = hardware.get("cpu", "the benchmark host")
    lines.append(f"**CPU host:** {cpu_host} (Colab VM). The CPU columns describe "
                 "that 2-core allocation; they are not a general claim about "
                 "OpenMP scaling.\n")
    if gpu_info.get("name") and gpu_info["name"] != "cpu-only":
        lines.append(f"**GPU:** {gpu_info['name']} (sm_{gpu_info.get('compute_capability','?')}). "
                     f"Assumed theoretical peak bandwidth: "
                     f"**{gpu_info.get('assumed_peak_gbs','?')} GB/s** "
                     f"(vendor spec assumed from the device name). Achieved "
                     f"bandwidth uses the no-reuse traffic model.\n")
    pending = os.path.join(RESULTS, "ell_optimization", "FULL_SWEEP_PENDING")
    if os.path.exists(pending):
        lines.append("**Data status:** this full sweep predates the ELL traversal "
                     "fix. Current ELL numbers are in "
                     "`results/ell_optimization/summary.md`; a full post-fix "
                     "sweep is still pending.\n")
    lines.append("GPU timings are medians over 50 CUDA-event iterations after "
                 "warmup; CPU timings are medians over 10 steady-clock "
                 "iterations. Kernel time excludes host-device transfers; "
                 "`transfer` is the separate H2D+D2H time.\n")
    lines.append("Bandwidth uses the no-reuse traffic model. Values above "
                 "100% of peak mean that model overcounts DRAM traffic because "
                 "the input vector is partly served from cache; `bw_lo_gbs` in "
                 "`bench.csv` is the compulsory-traffic lower bound.\n")

    # ---- headline: best non-baseline kernel per device/matrix/precision -----
    lines.append("## Headline: best kernel per device, matrix, precision\n")
    lines.append("| device | matrix | prec | best kernel | median ms | min ms | "
                 "GFLOP/s | BW lo GB/s | BW hi GB/s | % peak (hi) | transfer ms | "
                 "speedup |")
    lines.append("|--------|--------|------|-------------|----------:|-------:|"
                 "--------:|-----------:|-----------:|------------:|"
                 "------------:|--------:|")
    best_rows = {}
    for r in bench:
        if is_true(r["is_baseline"]):
            continue
        if r["matrix"] in SKIP_MATRICES:
            continue
        key = (r["device"], r["matrix"], r["precision"])
        cur = best_rows.get(key)
        if cur is None or float(r["median_ms"]) < float(cur["median_ms"]):
            best_rows[key] = r
    for key in sorted(best_rows):
        r = best_rows[key]
        pct = r["bw_pct_peak"] if r["device"] == "cuda" else "n/a"
        lines.append(
            f"| {device_label(r['device'])} | {r['matrix']} | {r['precision']} | "
            f"{r['kernel']} | {fmt(r['median_ms'])} | {fmt(r['min_ms'])} | "
            f"{fmt(r['gflops'])} | {fmt(r['bw_lo_gbs'])} | "
            f"{fmt(r['bw_hi_gbs'])} | {fmt(pct) if pct != 'n/a' else pct} | "
            f"{fmt(r['transfer_ms'])} | {fmt(r['speedup'],3)}x |"
        )

    # ---- speedup extremes ---------------------------------------------------
    ranked = sorted(
        (r for r in bench
         if not is_true(r["is_baseline"]) and r["matrix"] not in SKIP_MATRICES
         and float(r["speedup"] or 0) > 0),
        key=lambda r: float(r["speedup"]), reverse=True)
    if ranked:
        lines.append("\n## Speedup vs baseline - extremes\n")
        lines.append("| device | matrix | prec | kernel | speedup |")
        lines.append("|--------|--------|------|--------|--------:|")
        for r in ranked[:5] + ranked[-5:]:
            lines.append(
                f"| {device_label(r['device'])} | {r['matrix']} | {r['precision']} | "
                f"{r['kernel']} | {fmt(r['speedup'],3)}x |"
            )

    # ---- heuristic vs oracle ------------------------------------------------
    lines.append("\n## Heuristic vs measured oracle\n")
    if heur:
        by_dev = {}
        for r in heur:
            by_dev.setdefault(r.get("device", "cpu"), []).append(r)
        for dev, rows in by_dev.items():
            hits = sum(1 for r in rows if str(r["hit"]) == "1")
            n = len(rows)
            worst = max(float(r["slowdown"]) for r in rows) if rows else 1.0
            pct = 100.0 * hits / n if n else 0.0
            lines.append(
                f"- **{device_label(dev)}**: {hits}/{n} = {pct:.0f}% fastest; "
                f"worst slowdown {worst:.2f}x\n")
        lines.append("| device | matrix | chosen | oracle best | chosen ms | "
                     "best ms | hit | slowdown |")
        lines.append("|--------|--------|--------|-------------|----------:|"
                     "--------:|-----|---------:|")
        for r in heur:
            lines.append(
                f"| {device_label(r.get('device','cpu'))} | {r['matrix']} | "
                f"{r['chosen']} | {r['oracle_best']} | {fmt(r['chosen_ms'])} | "
                f"{fmt(r['best_ms'])} | {'yes' if str(r['hit'])=='1' else 'no'} | "
                f"{fmt(r['slowdown'],3)}x |"
            )
        misses = [r for r in heur if str(r["hit"]) != "1"]
        if misses:
            lines.append("\n### Selector misses\n")
            for r in misses:
                lines.append(
                    f"- **{r['matrix']}** ({device_label(r.get('device','cpu'))}): "
                    f"`{r['chosen']}` at {fmt(r['chosen_ms'])} ms vs "
                    f"`{r['oracle_best']}` at {fmt(r['best_ms'])} ms -> "
                    f"**{fmt(r['slowdown'],3)}x slower**.\n")
    else:
        lines.append("_results/heuristic.csv not found_\n")

    # ---- accuracy -----------------------------------------------------------
    lines.append("\n## Accuracy (max relative error, CSR SpMV)\n")
    if acc:
        lines.append("| matrix | fp32/fp32 | fp32/fp64 | fp64/fp64 |")
        lines.append("|--------|-----------|-----------|-----------|")
        modes = ["fp32/fp32", "fp32/fp64", "fp64/fp64"]
        by = {}
        for r in acc:
            if r["kernel"] != "csr_vector":
                continue
            by.setdefault(r["matrix"], {})[r["mode"]] = r["max_rel_err"]
        for mname in sorted(by):
            cells = " | ".join(fmt(by[mname].get(mode, "n/a")) for mode in modes)
            lines.append(f"| {mname} | {cells} |")
        lines.append("\nSee `docs/error_analysis.md` for the full discussion.\n")
    else:
        lines.append("_results/accuracy.csv not found_\n")

    return "\n".join(lines) + "\n", best_rows


def make_plot(best_rows):
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except Exception as exc:  # noqa: BLE001
        print(f"[report] matplotlib unavailable ({exc}); skipping gflops.png")
        return
    # Prefer GPU fp64; otherwise CPU fp64.
    for dev in ("cuda", "cpu"):
        labels, vals = [], []
        for (d, matrix, prec), r in sorted(best_rows.items()):
            if d == dev and prec == "fp64":
                labels.append(matrix)
                vals.append(float(r["gflops"]))
        if labels:
            fig, ax = plt.subplots(figsize=(9, 4.8))
            ax.bar(labels, vals, color="#3572A5" if dev == "cuda" else "#76B900")
            ax.set_ylabel(f"GFLOP/s ({device_label(dev)} best fp64 kernel)")
            ax.set_title("SpMVBench best-kernel throughput")
            plt.xticks(rotation=30, ha="right")
            fig.tight_layout()
            out = os.path.join(RESULTS, "gflops.png")
            fig.savefig(out, dpi=120)
            print(f"[report] wrote {out}")
            return


def main() -> int:
    os.makedirs(RESULTS, exist_ok=True)
    summary, best_rows = build_summary()
    with open(os.path.join(RESULTS, "summary.md"), "w", encoding="ascii") as f:
        f.write(summary)
    print("[report] wrote results/summary.md")
    make_plot(best_rows)
    return 0


if __name__ == "__main__":
    sys.exit(main())
